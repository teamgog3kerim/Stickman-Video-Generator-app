export function translate(locale: LanguageCode, source: string, values?: TranslationValues): string {
  const dictionary = locale === "en" ? undefined : translations[locale];
  let message = dictionary?.[source] ?? source;
  if (values) {
    for (const [key, value] of Object.entries(values)) {
      message = message.replaceAll(`{{${key}}}`, String(value));
    }
  }
  return message;
}

let activeLocale: LanguageCode = "en";
export function translateActive(source: string, values?: TranslationValues): string {
  return translate(activeLocale, source, values);
}

type LanguageContextValue = {
  locale: LanguageCode;
  setLocale: (locale: LanguageCode) => void;
  t: (source: string, values?: TranslationValues) => string;
};

const LanguageContext = createContext<LanguageContextValue>({
  locale: "en",
  setLocale: () => undefined,
  t: (source) => source,
});

function readInitialLocale(): LanguageCode {
  if (typeof window === "undefined") return "en";
  const requested = new URLSearchParams(window.location.search).get("lang");
  if (requested === "am" || requested === "ar") return requested;
  const stored = window.localStorage.getItem("stickman-director-locale");
  return stored === "am" || stored === "ar" ? stored : "en";
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<LanguageCode>(readInitialLocale);
  const setLocale = useCallback((next: LanguageCode) => {
    setLocaleState(next);
    if (typeof window !== "undefined") window.localStorage.setItem("stickman-director-locale", next);
  }, []);
  useEffect(() => {
    activeLocale = locale;
    document.documentElement.lang = locale === "am" ? "am-ET" : locale;
    document.documentElement.dir = languages.find((item) => item.code === locale)?.direction ?? "ltr";
  }, [locale]);
  activeLocale = locale;
  const t = useCallback((source: string, values?: TranslationValues) => translate(locale, source, values), [locale]);
  const value = useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useI18n() {
  return useContext(LanguageContext);
}

export function LanguageSwitcher({ label = "Language", testId = "select-language", onChange }: { label?: string; testId?: string; onChange?: (locale: LanguageCode) => void }) {
  const { locale, setLocale, t } = useI18n();
  return (
    <label className="language-switcher">
      <span>{t(label)}</span>
      <select value={locale} onChange={(event) => onChange ? onChange(event.target.value as LanguageCode) : setLocale(event.target.value as LanguageCode)} aria-label={t(label)} data-testid={testId}>
        {languages.map((language) => <option key={language.code} value={language.code}>{language.nativeName}</option>)}
      </select>
    </label>
  );
}

export function languageName(code: LanguageCode): string {
  if (code === "am") return "Amharic (አማርኛ)";
  if (code === "ar") return "Arabic (العربية)";
  return "English";
}

export function languageInstruction(code: LanguageCode): string {
  if (code === "am") {
    return "Amharic (አማርኛ): write natural, polished Amharic in the native Ethiopic script. Keep all narration, titles, on-screen text, and captions in Amharic; do not transliterate or switch languages unnecessarily.";
  }
  if (code === "ar") {
    return "Arabic (العربية): write clear, professional Modern Standard Arabic in Arabic script. Keep all narration, titles, on-screen text, and captions in Arabic; use culturally natural phrasing and do not transliterate.";
  }
  return "English: write clear, natural English throughout.";
}
